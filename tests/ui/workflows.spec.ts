test('automatic break-window preference starts on and persists off after reload',async({page})=>{
  await installDesktopFixture(page);await page.goto('/')
  await page.getByRole('button',{name:'Settings',exact:true}).click()
  await expect(page.getByLabel('Show break window when a reminder is due')).toBeChecked()
  await page.getByLabel('Show break window when a reminder is due').uncheck()
  await page.getByRole('button',{name:'Save settings'}).click()
  await expect(page.getByRole('status').filter({hasText:'Saved on this device'})).toBeVisible()
  expect((await commandCalls(page,'update_settings'))[0].args.settings).toMatchObject({showBreakWindow:false})
  await page.reload();await page.getByRole('button',{name:'Settings',exact:true}).click()
  await expect(page.getByLabel('Show break window when a reminder is due')).not.toBeChecked()
})
