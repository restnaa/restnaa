test('history shows separate outcomes and clear requires keyboard confirmation',async({page})=>{
  const errors:string[]=[];page.on('pageerror',error=>errors.push(error.message));page.on('console',msg=>{if(msg.type()==='error')errors.push(msg.text())})
  await installDesktopFixture(page);await page.goto('/')
  await page.getByRole('button',{name:'History',exact:true}).click()
  await page.getByText('All outcomes & how they count',{exact:true}).click()
  for(const name of ['Completed','Skipped','Snoozed','Unanswered'])await expect(page.getByText(name,{exact:true}).first()).toBeAttached()
  await page.getByLabel('Show history').selectOption('today')
  await expect(page.getByText('2026-10-21 – 2026-10-21',{exact:true})).toBeVisible()
  await page.getByRole('button',{name:'Settings',exact:true}).click()
  const clear=page.getByRole('button',{name:'Clear history…'})
  await clear.click();await expect(page.getByRole('dialog')).toBeVisible()
  await expect(page.getByRole('button',{name:'Keep history'})).toBeFocused()
  await page.keyboard.press('Shift+Tab');await expect(page.getByRole('button',{name:'Permanently clear history'})).toBeFocused()
  await page.keyboard.press('Escape');await expect(page.getByRole('dialog')).not.toBeVisible();await expect(clear).toBeFocused()
  expect(await commandCalls(page,'clear_history')).toHaveLength(0)
  await clear.click();await page.getByRole('button',{name:'Permanently clear history'}).click()
  await expect(page.getByRole('status').filter({hasText:'Local break history cleared'})).toBeVisible()
  expect(await commandCalls(page,'clear_history')).toMatchObject([{args:{confirmed:true}}])
  await page.getByRole('button',{name:'History',exact:true}).click()
  await expect(page.getByText(/No recorded outcomes in this period/)).toBeVisible()
  expect(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth)).toBe(false)
  if(test.info().project.name==='compact')expect(await page.evaluate(()=>matchMedia('(prefers-reduced-motion: reduce)').matches)).toBe(true)
  expect(errors).toEqual([])
})

